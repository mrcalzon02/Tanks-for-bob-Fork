-- prototypes/compatibility/mechanicus-locale.lua
-- Conditional Mechanicus/40K-style locale overlay for tanks_for_bob_fork.
-- Locale files cannot be conditionally loaded by dependency, so this patch assigns localised_name/localised_description at data stage.

local mechanicus_mods = {
  "MechanicusMiniMAX",   -- Mechanicus (Rebuild)
  "mechanicus-reborn",   -- Mechanicus Reborn, Factorio 2.0 fork
  "Mechanicus",          -- legacy/alternate naming fallback
  "mechanicus"           -- lowercase fallback
}

local active = false
for _, mod_name in pairs(mechanicus_mods) do
  if mods[mod_name] then
    active = true
    break
  end
end

if not active then return end

local function patch_any_named_prototype(name, field, locale_category)
  for _, prototypes in pairs(data.raw) do
    if prototypes[name] then
      prototypes[name][field] = {locale_category .. "." .. name}
    end
  end
end

local function patch_direct(type_name, name, field, locale_category)
  if data.raw[type_name] and data.raw[type_name][name] then
    data.raw[type_name][name][field] = {locale_category .. "." .. name}
  end
end

